ORDEM = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789./:?-!()"
assert all(c in G for c in ORDEM) and len(set(ORDEM)) == len(ORDEM)
out = []
for c in ORDEM:
    rows = G[c]; assert len(rows) == 7 and all(len(r) == 5 for r in rows), c
    for r in rows:
        b = 0
        for i, ch in enumerate(r):
            if ch == '#': b |= 0x80 >> (i + 1)   # coluna 0 vazia, letra nos bits 6-2
        out.append(b)
    out.append(0)                                  # 8.a linha vazia
with open('fonte.asm', 'w') as f:
    f.write("; fonte.asm: gerado pelo fonte.py (letra 5x7 propria). Ordem: \"%s\"\n" % ORDEM.replace('"','\\"'))
    f.write("fonte_ordem: db \"%s\",0\n" % ORDEM)
    f.write("fonte:\n")
    for i in range(0, len(out), 8):
        f.write("  db " + ",".join("%d" % x for x in out[i:i+8]) + "\n")
print(len(ORDEM), "caracteres,", len(out), "bytes")
