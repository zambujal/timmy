ordem = [chr(c) for c in range(32, 128)]
ordem[96 - 32] = '£'; ordem[127 - 32] = '©'
assert all(c in G for c in ordem), [c for c in ordem if c not in G]
out = bytearray()
for c in ordem:
    for r in G[c]:
        b = 0
        for i, ch in enumerate(r):
            if ch == '#': b |= 0x80 >> i
        out.append(b)
assert len(out) == 768
open('font8.bin', 'wb').write(out)
# imagem para ver
from PIL import Image
im = Image.new('1', (16 * 8 * 3, 6 * 8 * 3), 1)
for k, c in enumerate(ordem):
    x0, y0 = (k % 16) * 24, (k // 16) * 24
    for y, r in enumerate(G[c]):
        for x, ch in enumerate(r):
            if ch == '#':
                for dy in range(3):
                    for dx in range(3): im.putpixel((x0 + x * 3 + dx, y0 + y * 3 + dy), 0)
im.save('letra8.png')
